export const getRandomPhrase = (category: keyof typeof MOVEMENT_PHRASES, ctx: MovementContext): string => {
  const phrases = MOVEMENT_PHRASES[category];
  if (!phrases || phrases.length === 0) return "";
  const seed = `${ctx.summary.dayIndex}|${category}|${ctx.activeMinutes}|${ctx.activityTypes.join(",")}`;
  let hash = 2166136261;
  for (let i = 0; i < seed.length; i++) hash = Math.imul(hash ^ seed.charCodeAt(i), 16777619) >>> 0;
  return phrases[hash % phrases.length](ctx);
};
