// Pseudo-random deterministic selector based on dayIndex + seed to prevent flashing while maintaining variety
export function pickVariant(variants: string[], seed: number = 0): string {
  if (!variants || variants.length === 0) return "";
  const index = Math.abs(seed) % variants.length;
  return variants[index];
}

