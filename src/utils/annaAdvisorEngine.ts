/**
 * Builds a 3-paragraph holistic analysis for the Balance Tab without generic greetings.
 */
export function buildAnnaBalanceAnalysis(input: AnnaAnalysisInput, daySeed: number = 0): string {
  // 1. Intro sentence
  const introText = pickVariant(BALANCE_INTRO_VARIANTS, daySeed);

  // 2. Food & Fiber paragraph
  let foodText = "";
  const topIngText = input.topIngredients && input.topIngredients.length > 0
    ? input.topIngredients.slice(0, 3).join(", ")
    : "цельных растительных компонентов";

  if (input.totalFiber >= 35) {
    foodText = pickVariant(BALANCE_FIBER_HIGH_VARIANTS, daySeed + 1);
  } else if (input.totalFiber >= 15) {
    foodText = pickVariant(BALANCE_FIBER_MID_VARIANTS, daySeed + 2);
  } else {
    foodText = pickVariant(BALANCE_FIBER_LOW_VARIANTS, daySeed + 3);
  }
  foodText = foodText
    .replace("{totalCalories}", String(input.totalCalories))
    .replace("{totalProtein}", String(input.totalProtein))
    .replace("{totalFiber}", String(input.totalFiber))
    .replace("{topIngredients}", topIngText);

  // 3. Micros & Antioxidant sentence
  let microText = "";
  if (input.leaderName && (input.leaderPct ?? 0) > 0) {
    microText = pickVariant(BALANCE_MICROS_VARIANTS, daySeed + 4)
      .replace("{leaderName}", input.leaderName)
      .replace("{leaderPct}", String(Math.round(input.leaderPct || 0)));
  }

  // 4. Biometrics & Pressure sentence
  let bioText = "";
  if (input.effWeight && input.effWeight > 0) {
    const bpStr = input.effSystolic && input.effDiastolic ? `, давление **${input.effSystolic}/${input.effDiastolic}**` : "";
    bioText = pickVariant(BALANCE_BIOMETRICS_VARIANTS, daySeed + 5)
      .replace("{effWeight}", String(input.effWeight))
      .replace("{effBP}", bpStr);
  }

  // Combine into clear, spacious paragraphs
  const parts = [introText, foodText];
  if (microText || bioText) {
    parts.push([microText, bioText].filter(Boolean).join(" "));
  }

  return parts.join("\n\n");
}

/**
 * Builds tab-specific commentary for Tabs 2-6.
 */
export function buildAnnaTabAnalysis(tabId: string, input: AnnaAnalysisInput, daySeed: number = 0): string {
  switch (tabId) {
    case "scales":
      return pickVariant(SCALES_ANALYSIS_VARIANTS, daySeed);
    case "kbju":
      return pickVariant(KBJU_ANALYSIS_VARIANTS, daySeed);
    case "micro":
      return pickVariant(MICRO_ANALYSIS_VARIANTS, daySeed);
    case "composition":
      return pickVariant(COMPOSITION_ANALYSIS_VARIANTS, daySeed);
    case "dynamics":
      return pickVariant(DYNAMICS_ANALYSIS_VARIANTS, daySeed);
    case "balance":
    default:
      return buildAnnaBalanceAnalysis(input, daySeed);
  }
}

/**
 * Builds empathetic, non-alarmist hydration recommendation reasoning.
 */
export function buildHydrationReasoning(input: AnnaAnalysisInput, daySeed: number = 0): string {
  const isEvening = (input.remainingMinutes <= 240); // within 4h of sleep window
  const isSuccess = input.effWater >= input.waterTarget && input.waterTarget > 0;

  if (isSuccess) {
    return pickVariant(HYDRATION_SUCCESS_VARIANTS, daySeed)
      .replace("{effWater}", String(input.effWater));
  }

  if (isEvening) {
    const remaining = Math.max(0, input.waterTarget - input.effWater);
    return pickVariant(HYDRATION_EVENING_VARIANTS, daySeed)
      .replace("{effWater}", String(input.effWater))
      .replace("{waterRemaining}", String(remaining));
  }

  // Day deficit
  const remaining = Math.max(0, input.waterTarget - input.effWater);
  return pickVariant(HYDRATION_DAY_DEFICIT_VARIANTS, daySeed)
    .replace("{effWater}", String(input.effWater))
    .replace("{expectedWater}", String(input.expectedWaterByNow))
    .replace("{deficitNow}", String(input.deficitNow))
    .replace("{waterRemaining}", String(remaining))
    .replace("{waterTarget}", String(input.waterTarget))
    .replace("{paceNeeded}", String(input.paceNeeded));
}
