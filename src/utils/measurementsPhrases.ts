export const getRandomPhrase = (category: keyof typeof MEASUREMENT_PHRASES, ctx: MeasurementContext): string => {
  const phrases = MEASUREMENT_PHRASES[category];
  if (!phrases || phrases.length === 0) return "";
  const randomIndex = Math.floor(Math.random() * phrases.length);
  return phrases[randomIndex](ctx);
};