export type SleepPhraseCategory = keyof typeof SLEEP_PHRASES;
type SleepPhrase = string | ((ctx: SleepContext) => string);

export const getRandomSleepPhrase = (
  category: SleepPhraseCategory,
  ctx: SleepContext,
): string => {
  const phrases = SLEEP_PHRASES[category] as readonly SleepPhrase[];
  if (!phrases.length) return "";
  const phrase = pick(phrases);
  return typeof phrase === "function" ? phrase(ctx) : phrase;
};
