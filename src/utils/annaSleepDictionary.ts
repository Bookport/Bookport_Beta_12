export const pick = <T>(items: readonly T[]): T => {
  if (items.length === 0) throw new Error("Cannot pick from an empty phrase collection");
  return items[Math.floor(Math.random() * items.length)];
};

export const formatSleep = (minutes: number): string => {
  const value = Math.max(0, Math.round(minutes || 0));
  return `${Math.floor(value / 60)} ч ${value % 60} мин`;
};

const decline = (value: number, one: string, few: string, many: string): string => {
  const absolute = Math.abs(Math.trunc(value));
  const mod100 = absolute % 100;
  const mod10 = absolute % 10;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
};

export const declineDays = (value: number): string => decline(value, "день", "дня", "дней");
const declineDaysGenitive = (value: number): string => decline(value, "дня", "дней", "дней");
const declineHours = (value: number): string => decline(value, "час", "часа", "часов");
const declineMinutes = (value: number): string => decline(value, "минута", "минуты", "минут");

export const formatSleepWords = (minutes: number): string => {
  const value = Math.max(0, Math.round(minutes || 0));
  const hours = Math.floor(value / 60);
  const rest = value % 60;
  if (hours === 0) return `${rest} ${declineMinutes(rest)}`;
  if (rest === 0) return `${hours} ${declineHours(hours)}`;
  return `${hours} ${declineHours(hours)} ${rest} ${declineMinutes(rest)}`;
};

export const sleepDeficit = (ctx: SleepContext): number =>
  Math.max(0, ctx.sleepGoalMinutes - ctx.sleepMinutes);

export const sleepSurplus = (ctx: SleepContext): number =>
  Math.max(0, ctx.sleepMinutes - ctx.sleepGoalMinutes);

