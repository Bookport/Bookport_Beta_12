export function getAnnaWaterPhrase(drankToday: number, dailyGoal: number, hoursSinceLastDrink: number, lastDrinkVolume: number): string {
  const left = Math.max(0, dailyGoal - drankToday);
  
  let state: keyof typeof waterPhrases;
  
  if (drankToday === 0) {
    state = "MORNING_START";
  } else if (drankToday >= dailyGoal) {
    state = "GOAL_ACHIEVED";
  } else if (drankToday >= dailyGoal * 0.85) {
    state = "ALMOST_THERE";
  } else if (hoursSinceLastDrink > 2.5) {
    state = "LONG_GAP_WARNING";
  } else {
    state = "ON_TRACK";
  }

  const phrases = waterPhrases[state];
  const phrase = phrases[Math.floor(Math.random() * phrases.length)];

  return phrase
    .replace(/{dailyGoal}/g, dailyGoal.toString())
    .replace(/{drankToday}/g, drankToday.toString())
    .replace(/{left}/g, left.toString())
    .replace(/{hoursSinceLastDrink}/g, Math.round(hoursSinceLastDrink).toString())
    .replace(/{lastDrinkVolume}/g, lastDrinkVolume.toString());
}
