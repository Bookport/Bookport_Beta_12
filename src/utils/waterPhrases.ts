// ПРАВИЛА ДВИЖКА (реализуются ВНЕ этого файла):
// - coachingPct = timePct ?? pct.
// - Сегодня: zero (amount===0) → critical (<50) → behind (50–69) →
//   mild (70–99) → optimum (100–149) → excess (>=150).
// - История: абсолютные границы 0 / 50 / 100 / 150 по pct.
// - Кросс-блоки разрешены только в critical, при amount > 0.
// - При amount===0 выводится только base_zero, без кросс-блоков.
// - Нельзя собирать больше одной базовой оценки за один совет.
// - В UI абсолютная дневная цель и прогресс-бар не меняются.
