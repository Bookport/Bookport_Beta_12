export interface WaterContext {
  userName: string;
  userGender?: 'male' | 'female';
  waterStatus: 'zero' | 'deficit' | 'optimum' | 'excess';
  pct: number;
  amount: number;
  latestBristol: number | null;
  yesterdayFiber: number;
  latestMeasurements?: {
    pulseAvg: number | null;
    systolic: number | null;
    diastolic: number | null;
    weightAvg: number | null;
    weightDelta: number | null;
    tonus: 'low' | 'normal' | 'high' | 'no_data';
  };
}

export const getRandomPhrase = (phrases: string[], ctx: WaterContext): string => {
  if (!phrases || phrases.length === 0) return '';
  const randomIndex = Math.floor(Math.random() * phrases.length);
  return phrases[randomIndex].replace(/{name}/g, ctx.userName);
};

