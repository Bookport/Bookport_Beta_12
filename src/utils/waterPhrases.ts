//
// ПРАВИЛА ДВИЖКА (реализуются ВНЕ этого файла):
// - coachingPct = timePct ?? pct.
// - Сегодня: zero (amount===0) → critical (<50) → behind (50–69) →
//   mild (70–99) → optimum (100–149) → excess (>=150).
// - История: абсолютные границы 0 / 50 / 100 / 150 по pct.
// - Кросс-блоки разрешены только в critical, при amount > 0.
// - При amount===0 выводится только base_zero, без кросс-блоков.
// - Нельзя собирать больше одной базовой оценки за один совет.
// - В UI абсолютная дневная цель и прогресс-бар не меняются.
// ============================================================================

export interface WaterContext {
  userName: string;
  userGender?: 'male' | 'female';
  waterStatus: 'zero' | 'deficit' | 'optimum' | 'excess';
  pct: number;
  amount: number;
  latestBristol: number | null;
  yesterdayFiber: number;
  latestMeasurements?: {
    pulseAvg: number | null;
    systolic: number | null;
    diastolic: number | null;
    weightAvg: number | null;
    weightDelta: number | null;
    tonus: 'low' | 'normal' | 'high' | 'no_data';
  };
}

export const getRandomPhrase = (phrases: string[], ctx: WaterContext): string => {
  if (!phrases?.length) return '';
  return phrases[Math.floor(Math.random() * phrases.length)].replace(/{name}/g, ctx.userName);
};

