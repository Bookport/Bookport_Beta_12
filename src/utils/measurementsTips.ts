export function getDailyMeasurementTip(): string {
  const MOSCOW_OFFSET_MS = 3 * 60 * 60 * 1000;
  const mskNow = new Date(Date.now() + MOSCOW_OFFSET_MS);
  const year = mskNow.getUTCFullYear();
  const month = mskNow.getUTCMonth();
  const date = mskNow.getUTCDate();
  const dayNumber = Math.floor(Date.UTC(year, month, date) / (24 * 60 * 60 * 1000));
  const index = ((dayNumber % measurementTips.length) + measurementTips.length) % measurementTips.length;
  return measurementTips[index];
}