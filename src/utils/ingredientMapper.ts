// Генерирует кандидаты для поиска: точное имя → имя без модификаторов →
// последовательное усечение до корня → отдельные базовые слова.
function candidateKeys(name: string): string[] {
  const keys: string[] = [];
  const push = (k: string) => {
    if (k && !keys.includes(k)) keys.push(k);
  };

  const n = normalize(name);
  push(n);

  const strippedWords = n.split(/\s+/).filter((w) => !MODIFIER_WORDS.has(w));
  const stripped = strippedWords.join(" ");
  push(stripped);

  // Усечение по последнему слову (ловит модификаторы в конце и многословные названия)
  for (const base of [stripped, n]) {
    if (!base) continue;
    const parts = base.split(/\s+/);
    for (let i = parts.length - 1; i >= 1; i--) {
      push(parts.slice(0, i).join(" "));
    }
  }

  // Каждое базовое слово как самостоятельный кандидат
  for (const w of strippedWords) {
    push(w);
  }

  return keys;
}

export function getIngredientImage(name: string): string | null {
  if (!name) return null;

  // 1. Точное имя, имя без модификаторов, усечение до корня, базовые слова.
  //    Сначала сохраняется поиск по точному имени (специфичные картинки для составных названий).
  for (const candidate of candidateKeys(name)) {
    if (imageMap[candidate]) return imageMap[candidate];
    const aliased = ALIASES[candidate];
    if (aliased) {
      const aliasKey = normalize(aliased);
      if (imageMap[aliasKey]) return imageMap[aliasKey];
    }
  }

  // 2. Fallback to alias mapper (handles "жареная курица" → "куриная грудка")
  const resolved = getIngredientAlias(name);
  if (resolved !== name) {
    const resolvedKey = normalize(resolved);
    if (imageMap[resolvedKey]) return imageMap[resolvedKey];
    const aliased2 = ALIASES[resolved];
    if (aliased2) {
      const aliasKey2 = normalize(aliased2);
      if (imageMap[aliasKey2]) return imageMap[aliasKey2];
    }
  }

  return null;
}
