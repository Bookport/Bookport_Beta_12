export function normalize(name: string): string {
  return name
    .toLowerCase()
    .replace(/\.(webp|png)$/i, "")
    .replace(/_*результат$/i, "")
    .replace(/\)+$/, "")
    .replace(/_+$/, "")
    .replace(/[_\s]+/g, " ")
    .replace(/ё/g, "е")
    .trim();
}

