export interface DigestionMeasurements {
  pulseAvg: number | null;
  systolic: number | null;
  diastolic: number | null;
  weightAvg: number | null;
  weightDelta: number | null;
  tonus: 'low' | 'normal' | 'high' | 'no_data';
  triad: {
    wellbeing: 'bad' | 'normal' | 'good';
    energy: 'low' | 'normal' | 'high';
    mood: 'bad' | 'normal' | 'good';
  } | null;
}

export interface DigestionContext {
  userName: string;
  userGender?: 'male' | 'female';
  worstBristol: number;
  latestComfort: 'easy' | 'normal' | 'hard' | null;
  problemDishName?: string;
  symptoms: string[];
  latestSymptoms: string[];
  waterStatus: 'zero' | 'deficit' | 'optimum' | 'excess';
  movementStatus: 'sedentary' | 'light' | 'active' | 'athlete';
  latestMeasurements?: DigestionMeasurements;
}

export const getRandomPhrase = (phrases: string[], ctx: DigestionContext): string => {
  if (!phrases || phrases.length === 0) return '';
  const randomIndex = Math.floor(Math.random() * phrases.length);
  return phrases[randomIndex]
    .replace(/{name}/g, ctx.userName ?? '')
    .replace(/{problemDishName}/g, ctx.problemDishName ?? 'блюдо')
    .replace(/{symptoms}/g, (ctx.latestSymptoms ?? []).join(', '));
};

