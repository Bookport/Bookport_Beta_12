export const getRandomPhrase = (category: keyof typeof DIGESTION_PHRASES, ctx: DigestionContext): string => {
  const phrases = DIGESTION_PHRASES[category];
  if (!phrases || phrases.length === 0) return "";
  const randomIndex = Math.floor(Math.random() * phrases.length);
  return phrases[randomIndex](ctx);
};
